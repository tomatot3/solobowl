import {expect,test} from "@playwright/test";
import {recipeFixture} from "../fixtures/recipes";

test("retry preserves the selected serving and two dishes share the shopping total",async({page})=>{
  const one=recipeFixture(10,"published",{name:"测试菜甲"});
  const two=recipeFixture(11,"published",{name:"测试菜乙"});
  const recipes=[one,two];
  const path=(recipe:typeof one)=>`/recipes/${recipe.recipe.id}?version=${recipe.version.id}`;
  await page.route("**/api/v1/auth/session",route=>route.fulfill({status:401,json:{error:{code:"AUTH_REQUIRED"}}}));
  await page.route("**/api/v1/recipes/*/versions/*",route=>{
    const version=new URL(route.request().url()).pathname.split("/").at(-1);
    return route.fulfill({json:{data:recipes.find(recipe=>recipe.version.id===version)}});
  });
  let offline=true;
  let checks=0;
  await page.route("**/api/v1/recipe-versions/*/availability",route=>{
    checks++;
    if(offline)return route.abort("internetdisconnected");
    const version=new URL(route.request().url()).pathname.split("/").at(-2);
    return route.fulfill({json:{data:{allowed:true,checkedAt:new Date().toISOString(),contentHash:recipes.find(recipe=>recipe.version.id===version)?.version.contentHash}}});
  });
  await page.goto(path(one));
  const portion=page.getByRole("combobox",{name:"份量",exact:true});
  await portion.selectOption(one.version.servingOptions[1]!.id);
  await page.getByRole("button",{name:"加入待做"}).click();
  await expect(page.getByRole("main").getByRole("alert")).toBeVisible();
  await expect(portion).toHaveValue(one.version.servingOptions[1]!.id);
  offline=false;
  await expect(page).toHaveURL(/\/recipes\//);
  expect(checks).toBe(1);
  await page.getByRole("button",{name:"加入待做"}).click();
  await expect(page).toHaveURL(/\/cooking\/[a-f0-9-]+$/);
  const taskUrl=page.url();
  await page.goto(path(one));
  await page.getByRole("button",{name:"加入待做"}).click();
  await expect(page).toHaveURL(taskUrl);
  await page.goto(path(two));
  await page.getByRole("button",{name:"加入待做"}).click();
  await expect(page).toHaveURL(/\/cooking\/[a-f0-9-]+$/);
  await page.getByRole("link",{name:"为这道菜列采购清单"}).click();
  await page.getByLabel("测试菜甲").check();
  await page.getByRole("button",{name:"生成采购清单"}).click();
  await expect(page.getByText("菜谱用量 280 克")).toBeVisible();
  await page.getByLabel("手调数量").fill("300");
  await page.getByLabel("已购齐").check();
  await page.getByRole("button",{name:"保存此项"}).click();
  await expect(page.getByRole("button",{name:"保存此项"})).toBeEnabled();
  await page.reload();
  await expect(page.getByLabel("手调数量")).toHaveValue("300");
  await expect(page.getByLabel("已购齐")).toBeChecked();
  await page.goto(taskUrl);
  await page.getByLabel("审核份量").selectOption(one.version.servingOptions[0]!.id);
  await expect(page.getByText("TEST ONLY 100 g")).toBeVisible();
  await page.goto("/shopping");
  await expect(page.getByText("菜谱用量 200 克")).toBeVisible();
  await expect(page.getByText(/请复核手调数量/)).toBeVisible();
  await expect(page.getByLabel("手调数量")).toHaveValue("300");
  await expect(page.getByLabel("已购齐")).not.toBeChecked();
});
